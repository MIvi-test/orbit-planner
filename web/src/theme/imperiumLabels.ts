const STARMAP_LEVELS: Record<string, string> = {
  'Нет прямой замены': 'НЕЗАМЕНИМ',
  'Риск замены': 'СТОИТ',
  'В базовой проверке риск не найден': 'ПОД ЗАЩИТОЙ',
}

export function imperiumLabel(text: string): string {
  return LABELS[text] ?? STARMAP_LEVELS[text] ?? text
}

/** Возвращает функцию подписи: в теме «Империум» — из словаря, иначе исходный текст. */
export function useLabel(): (text: string) => string {
  const on = useImperium()
  return (text) => (on ? imperiumLabel(text) : text)
}

